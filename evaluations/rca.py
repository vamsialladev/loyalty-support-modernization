"""Writes `docs/root-cause-analysis.md`: one entry per defect, in the 11 categories of spec E.2 (LEG-01, LEG-03).

Causes and consequences come from the pre-registered catalog. Frequencies and results come from stored runs, so the
document can't drift from the data.

    uv run python -m evaluations.rca
"""

from __future__ import annotations

import re
import sys

from evaluations.compare import load_run
from evaluations.final_report import CATALOG
from evaluations.run import DATASET, RESULTS, read_labels
from evaluations.scoring import case_success, correct_action, expected_points, false_approval, false_denial

OUT = CATALOG.parent / "root-cause-analysis.md"
CATEGORIES = {
    "D01": "Missing or incorrect source data",
    "D02": "Integration failure",
    "D03": "Missing or incorrect source data",
    "D04": "Incorrect rules",
    "D05": "Integration failure",
    "D06": "Delayed upstream",
    "D07": "Fragmented UI",
    "D08": "Outdated policy configuration",
    "D09": "Outdated policy configuration",
    "D10": "Training or process issue",
    "D11": "Training or process issue",
    "D12": "Poor search",
    "D13": "Poor search",
    "D14": "Excessive manual work",
    "D15": "Outdated policy configuration",
    "D16": "Ambiguous language",
    "D17": "Poor search",
    "D18": "Ambiguous language",
    "D19": "Ambiguous language",
    "D20": "Training or process issue",
    "D21": "Incorrect rules",
    "D22": "Fragmented UI",
    "D23": "Ambiguous language",
    "D24": "Missing or incorrect source data",
    "D25": "Missing or incorrect source data",
}
ALL_CATEGORIES = (
    "Missing or incorrect source data",
    "Delayed upstream",
    "Integration failure",
    "Incorrect rules",
    "Outdated policy configuration",
    "Poor search",
    "Ambiguous language",
    "Fragmented UI",
    "Excessive manual work",
    "Training or process issue",
    "Unknown",
)
NON_AI = {
    "D16": "Partly. Arm B handles it when the member names the other stay. A model reads it without asking.",
    "D18": "Mostly. A nickname list handles common cases.",
    "D19": "No, not fully. Arm B asks, and can't read a free-text answer.",
    "D20": "Process: route a mixed message to a person. A model avoids the handoff.",
    "D22": "Mostly. Clean documents are read by rules. Noisy photos need vision.",
    "D23": "Process: route to a person who reads the language. A model avoids the handoff.",
}


def catalog_details() -> dict[str, list[str]]:
    rows = {}
    for line in CATALOG.read_text(encoding="utf-8").splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if re.fullmatch(r"D\d\d", cells[0]) and len(cells) >= 11:
            rows[cells[0]] = cells
    return rows


def main() -> int:
    labels = read_labels("heldout", DATASET)
    deterministic, live = RESULTS / "deterministic", RESULTS / "live"
    a = {r.case_id: r for r in load_run(deterministic / "a-heldout").results}
    b = {r.case_id: r for r in load_run(deterministic / "b-heldout").results}
    c = {r.case_id: r for r in load_run(live / "c-heldout-r1").results}
    details = catalog_details()
    lines = [
        "# Root-cause analysis (LEG-01, LEG-03; spec E.2)",
        "",
        "> **SYNTHETIC data, simulated engagement.** Generated by `evaluations/rca.py`. Causes come from "
        "`docs/legacy-defect-catalog.md`, which were written before any arm existed, so this checks them rather than "
        "discovers them. A real engagement would find causes from a customer's data. Results are on the held-out "
        "split, "
        "with arm C's first of three live runs shown: the three don't differ. Frequencies are configurable "
        "assumptions.",
        "",
        "## Failures by category",
        "",
        "| Category | Defects | Arm A held-out cases failed |",
        "|---|---|---|",
    ]
    for category in ALL_CATEGORIES:
        defects = sorted(d for d, name in CATEGORIES.items() if name == category)
        failed = sum(
            1
            for case, result in a.items()
            if set(labels[case]["scenarios"]) & set(defects) and not case_success(result, labels[case])
        )
        lines.append(f"| {category} | {', '.join(defects) or 'none'} | {failed} |")
    lines += [
        "",
        "**Not every problem is an AI opportunity.** Most of these are fixed by data cleanup, an integration, a "
        "corrected "
        "rule, a better screen or a process control, and arm B shows it: "
        "`benchmarks/reports/heldout/predicted-vs-actual.md`.",
        "",
        "## Each defect",
        "",
    ]
    for defect in sorted(CATEGORIES):
        row = details.get(defect)
        if row is None:
            continue
        cases = sorted(case for case in a if defect in labels[case]["scenarios"])
        lines += [f"### {defect}: {row[1]}", "", f"- **Category:** {CATEGORIES[defect]}.", f"- **Cause:** {row[2]}."]
        lines += [f"- **Frequency in the synthetic history:** {row[4]}. **Business consequence:** {row[7]}."]
        lines += [f"- **Member consequence:** {row[6]}."]
        if cases:
            sample = cases[0]
            expected = expected_points(labels[sample])
            result = a[sample]
            lines += [
                f"- **Reproduce:** `uv run python -m evaluations.run --arm a --split heldout --cases {sample} "
                "--name repro --confirm-frozen`.",
                f"- **Expected against actual, {sample}:** expected `{labels[sample]['next_action']}`, "
                f"outcome `{labels[sample]['expected_outcome']}`, points {expected}. Arm A: `{result.first_action}`, "
                f"`{result.outcome}`, points {dict(result.final_points)}.",
                "- **Evidence, case success on held-out:** "
                f"A {sum(case_success(a[x], labels[x]) for x in cases)}/{len(cases)}, "
                f"B {sum(case_success(b[x], labels[x]) for x in cases)}/{len(cases)}, "
                f"C {sum(case_success(c[x], labels[x]) for x in cases)}/{len(cases)}. "
                f"Arm A: first action right {sum(correct_action(a[x], labels[x]) for x in cases)}, "
                f"over-credits {sum(false_approval(a[x], labels[x]) for x in cases)}, "
                f"under-credits {sum(false_denial(a[x], labels[x]) for x in cases)}.",
            ]
        else:
            lines += ["- **Evidence:** not in held-out. It costs steps, not accuracy (catalog)."]
        lines += [f"- **Recommended intervention:** {row[8]}."]
        if defect in NON_AI:
            lines += [f"- **Is a non-AI fix enough?** {NON_AI[defect]}"]
        lines += [""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
