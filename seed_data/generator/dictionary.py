"""Render `docs/data-dictionary.md` from the Pydantic models (every field has a description)."""

from typing import Any

from seed_data.generator.models import DICTIONARY_MODELS

HEADER = """# Data dictionary (dataset v1)

> Generated by `python -m seed_data.generator dictionary` from `seed_data/generator/models.py`. Do not edit by hand:
> `tests/test_generator.py` fails if this file is out of date. **SYNTHETIC** data throughout; nothing is derived from
> real records. Timestamps are UTC (`YYYY-MM-DDTHH:MM:SSZ`), dates `YYYY-MM-DD`, money in integer US cents.
> Upstream (customer) field names for each canonical field are in `config/customers/hg-demo.yaml`.
> Where each file lives and who may read it: operational data `seed_data/v1/` (the mock API reads it from
> Milestone 4); benchmark inputs `benchmarks/datasets/v1/<split>.jsonl`; ground truth
> `benchmarks/datasets/v1/labels/` (evaluation code only; the application can never read it).
"""


def _type(annotation: Any) -> str:
    text = str(annotation).replace("typing.", "")
    for noise in ("<class '", "'>"):
        text = text.replace(noise, "")
    return text.replace("|", "or")


def render_dictionary() -> str:
    lines = [HEADER]
    for location, model in DICTIONARY_MODELS:
        lines += [
            f"## {model.__name__}",
            "",
            (model.__doc__ or "").strip(),
            "",
            f"Location: `{location}`",
            "",
            "| Field | Type | Required | Description |",
            "|---|---|---|---|",
        ]
        for name, info in model.model_fields.items():
            required = "yes" if info.is_required() else "no"
            description = (info.description or "").replace("|", "/")
            lines.append(f"| `{name}` | {_type(info.annotation)} | {required} | {description} |")
        lines.append("")
    return "\n".join(lines)
