"""Machine clients for the protocol services, created in a local Keycloak through its admin API (RFC-0004; ADR-0071).

Not in the realm import file on purpose: an imported realm that lists client scopes replaces Keycloak's built-in ones,
and console sign-in needs those. So the scopes and clients are added at run time, the same way the Milestone 9 check
adds its throwaway users. Each client gets:

- client-credentials only (a service account), no browser sign-in;
- one default scope per protocol, which appears in the token's `scope` claim;
- an audience mapper naming the one service it may call (RFC 8707: the token is for that resource only);
- a fixed `customer_id` claim, which is the only place a protocol service learns the caller's customer.

Secrets are generated by Keycloak and returned to the caller in memory; nothing here prints or saves them.
"""

from __future__ import annotations

from dataclasses import dataclass

import httpx

REALM = "hotel"
SCOPES = ("loyalty.read", "loyalty.case.read", "reservation.evidence")


@dataclass(frozen=True)
class MachineClient:
    client_id: str
    secret: str
    audience: str
    scopes: tuple[str, ...]
    customer_id: str


def admin_client(keycloak: str, admin_password: str) -> httpx.Client:
    token = httpx.post(
        f"{keycloak}/realms/master/protocol/openid-connect/token",
        data={"grant_type": "password", "client_id": "admin-cli", "username": "admin", "password": admin_password},
        timeout=30,
    ).json()["access_token"]
    return httpx.Client(
        base_url=f"{keycloak}/admin/realms/{REALM}", headers={"Authorization": f"Bearer {token}"}, timeout=30
    )


def ensure_scopes(admin: httpx.Client) -> dict[str, str]:
    """Scope name → Keycloak ID, creating any that are missing."""
    existing = {s["name"]: s["id"] for s in admin.get("/client-scopes").json()}
    for name in SCOPES:
        if name not in existing:
            created = admin.post(
                "/client-scopes",
                json={
                    "name": name,
                    "protocol": "openid-connect",
                    "attributes": {"include.in.token.scope": "true", "display.on.consent.screen": "false"},
                },
            )
            created.raise_for_status()
            existing[name] = created.headers["location"].rsplit("/", 1)[-1]
    return existing


def create_machine_client(
    admin: httpx.Client, client_id: str, audience: str, scopes: tuple[str, ...], customer_id: str = "hg-demo"
) -> MachineClient:
    ids = ensure_scopes(admin)
    created = admin.post(
        "/clients",
        json={
            "clientId": client_id,
            "enabled": True,
            "publicClient": False,
            "serviceAccountsEnabled": True,
            "standardFlowEnabled": False,
            "directAccessGrantsEnabled": False,
            "implicitFlowEnabled": False,
            "protocolMappers": [
                {
                    "name": "audience",
                    "protocol": "openid-connect",
                    "protocolMapper": "oidc-audience-mapper",
                    "config": {
                        "included.custom.audience": audience,
                        "access.token.claim": "true",
                        "id.token.claim": "false",
                    },
                },
                {
                    "name": "customer",
                    "protocol": "openid-connect",
                    "protocolMapper": "oidc-hardcoded-claim-mapper",
                    "config": {
                        "claim.name": "customer_id",
                        "claim.value": customer_id,
                        "jsonType.label": "String",
                        "access.token.claim": "true",
                        "id.token.claim": "false",
                    },
                },
            ],
        },
    )
    created.raise_for_status()
    internal = created.headers["location"].rsplit("/", 1)[-1]
    for name in scopes:
        admin.put(f"/clients/{internal}/default-client-scopes/{ids[name]}").raise_for_status()
    secret = str(admin.get(f"/clients/{internal}/client-secret").json()["value"])
    return MachineClient(client_id, secret, audience, scopes, customer_id)


def set_enabled(admin: httpx.Client, client_id: str, enabled: bool) -> None:
    found = admin.get("/clients", params={"clientId": client_id}).json()[0]
    found["enabled"] = enabled
    admin.put(f"/clients/{found['id']}", json=found).raise_for_status()


def client_credentials_token(keycloak: str, client: MachineClient) -> httpx.Response:
    return httpx.post(
        f"{keycloak}/realms/{REALM}/protocol/openid-connect/token",
        data={"grant_type": "client_credentials", "client_id": client.client_id, "client_secret": client.secret},
        timeout=30,
    )
